const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, de };

export function resolveLocale(systemLocale: string): Locale {
  return systemLocale.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function translate(locale: Locale, key: MessageKey, params?: Record<string, string | number>): string {
  const template = dictionaries[locale][key] ?? en[key];
  return params ? template.replace(/\{(\w+)\}/g, (m, name: string) => String(params[name] ?? m)) : template;
}
